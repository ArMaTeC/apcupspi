import glob


def _load_json(path):
    try:
        with open(path) as f:
            return json.load(f)
    except Exception:
        return {}


def do_update_settings(form, user=None):
    """Persist the [update] options from the Update Settings card into
    nmc.conf — the updater reads them from the file directly."""
    def v(k):
        return form.get(k, [""])[0].strip()
    errs = []
    if v("urepo") and not re.fullmatch(
            r"[A-Za-z0-9_.\-]+/[A-Za-z0-9_.\-]+", v("urepo")):
        errs.append("repository must look like owner/name")
    if v("ubranch") and not re.fullmatch(
            r"[A-Za-z0-9._/\-]{1,64}", v("ubranch")):
        errs.append("invalid branch name")
    if v("uchannel") not in ("releases", "branch"):
        errs.append("invalid channel")
    if v("uverify") not in ("checksum", "strict", "0"):
        errs.append("invalid verify mode")
    if errs:
        return ("msg-err", "; ".join(errs))
    for key, val in (("repo", v("urepo")), ("branch", v("ubranch")),
                     ("channel", v("uchannel")), ("verify", v("uverify")),
                     ("autocheck",
                      "1" if form.get("uautocheck") else "0")):
        conf_set("update", key, val)
    log_event("NMC: Update settings changed by %s." % (user or WEB_USER))
    return ("msg-ok", "Update settings saved.")


def do_update_token(form, user=None):
    """Generate/clear the [web] api_token used by monitoring clients."""
    act = form.get("act", [""])[0]
    if act == "generate":
        tok = secrets.token_urlsafe(24)
        conf_set("web", "api_token", tok)
        log_event("NMC: API token generated by %s." % (user or WEB_USER))
        return ("msg-ok", "API token generated.")
    if act == "clear":
        conf_set("web", "api_token", "")
        log_event("NMC: API token cleared by %s." % (user or WEB_USER))
        return ("msg-ok", "API token cleared.")
    return ("msg-err", "Unknown action.")


def update_lock_held():
    """True while the updater's flock is taken — the only reliable sign
    an apply/rollback is alive; the status file survives reboots and
    service kills."""
    try:
        fd = os.open(UPDATE_LOCK, os.O_RDONLY)
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError:
            os.close(fd)
            return True                # lock held — apply in progress
        fcntl.flock(fd, fcntl.LOCK_UN)
        os.close(fd)
    except OSError:
        pass                           # no lock file => nothing running
    return False


def update_running_live(uss):
    """A 'running' update-status survives a reboot — the file is only
    truth when the updater's lock is genuinely held."""
    return uss.get("state") == "running" and update_lock_held()


def update_status_view(uss) -> dict:
    """update-status.json as the UI should report it: 'running' is only
    real while the updater's lock is held (a persisted 'running' with a
    free lock means the updater died mid-run — e.g. a reboot), and a
    'queued' stamp expires when the systemd unit never gets going."""
    st = uss.get("state")
    if st == "running" and not update_lock_held():
        return dict(uss, state="interrupted")
    if st == "queued" and not update_lock_held():
        try:
            qts = float(uss.get("qts") or 0)
        except (TypeError, ValueError):
            qts = 0
        if time.time() - qts > 90:
            return dict(uss, state="failed",
                        msg="update service did not start")
    return uss


def update_busy():
    """An apply/rollback is queued or live — used to refuse starting a
    second update on top of one already in flight."""
    return update_status_view(_load_json(UPDATE_STATUS)).get("state") \
        in ("queued", "running")


def queue_update_status(msg):
    """Stamp update-status.json just before the updater unit starts —
    without it the apply console's first polls still read the previous
    run's terminal state and immediately jump back to About. logpos
    marks where this run's output begins so /progress can open on a
    fresh view instead of the last run's tail."""
    try:
        size = os.path.getsize(UPDATE_LOG)
    except OSError:
        size = 0
    try:
        tmp = UPDATE_STATUS + ".tmp"
        with open(tmp, "w") as f:
            json.dump({"state": "queued", "msg": msg, "from": "",
                       "to": "", "finished": 0, "qts": int(time.time()),
                       "logpos": size}, f)
        os.chmod(tmp, 0o640)
        os.replace(tmp, UPDATE_STATUS)
    except OSError:
        pass


def update_backups(state_dir="/var/lib/apc-nmc"):
    """Newest-first list of (dir, restored_version, epoch) for
    update-backup-* dirs — the rollback points --rollback restores."""
    out = []
    for d in sorted(glob.glob(
            os.path.join(state_dir, "update-backup-*")), reverse=True):
        if not os.path.isdir(d):
            continue
        try:
            with open(os.path.join(d, "meta")) as fh:
                meta = fh.read().split()
            ver = meta[0] if meta else "?"
            ts = int(meta[2]) if len(meta) > 2 else 0
        except (OSError, ValueError, IndexError):
            ver, ts = "?", 0
        out.append((d, ver, ts))
    # newest first — mirrors --rollback's ls -dt pick, using meta ts
    out.sort(key=lambda b: (b[2], b[0]), reverse=True)
    return out


def config_new_keys(default="/etc/apc-nmc/nmc.conf.default", live=None):
    """section.key names in nmc.conf.default that are unset (or only
    commented) in the live nmc.conf — options updates have shipped that
    the admin may want to review. Never exposes values."""
    cp_new = configparser.ConfigParser()
    cp_new.read(default)
    cp_live = configparser.ConfigParser()
    cp_live.read(CONF if live is None else live)
    return ["%s.%s" % (s, k) for s in cp_new.sections()
            for k in cp_new.options(s)
            if not (cp_live.has_section(s) and k in cp_live.options(s))]


def config_merge_defaults(default="/etc/apc-nmc/nmc.conf.default"):
    """Materialize defaults for section.key options shipped in
    nmc.conf.default that the live nmc.conf does not set — the updater
    runs this so new options appear in the config instead of only being
    listed as unset. Existing admin values are never touched; a key
    present only as a commented line is replaced in place. Doc comments
    immediately above a key are copied with it. Returns the merged
    section.key list."""
    try:
        with open(default) as f:
            dlines = f.read().splitlines()
    except OSError:
        return []
    wanted = []                          # (sec, key, val, doc-comments)
    sec, pend = None, []
    for ln in dlines:
        m = re.match(r"\s*\[\s*([^]]+)", ln)
        if m:
            sec, pend = m.group(1).strip(), []
            continue
        if sec is None:
            continue
        if not ln.strip():
            pend = []
            continue
        if ln.lstrip().startswith("#"):
            # keep doc comments; skip commented-out example keys
            if not re.match(r"#\s*[A-Za-z_0-9]+\s*=", ln):
                pend.append(ln.strip())
            continue
        k, sep, v = ln.partition("=")
        if not sep:
            pend = []
            continue
        wanted.append((sec, k.strip(), v.strip(), pend))
        pend = []
    try:
        with open(CONF) as f:
            lines = f.read().splitlines()
    except OSError:
        lines = []
    merged = []
    for sec, key, val, comments in wanted:
        cp = configparser.ConfigParser()
        cp.read_string("\n".join(lines))
        if cp.has_section(sec) and key in cp.options(sec):
            continue                                # admin already set it
        key_re = re.compile(r"^\s*#?\s*" + re.escape(key) + r"\s*=")
        ins = comments + ["%s = %s" % (key, val)]
        out, cur, done = [], "", False
        for line in lines:
            m = re.match(r"\s*\[\s*([^]]+)", line)
            if m:
                s = m.group(1).strip()
                if cur == sec and not done:         # leaving our section
                    out += ins                      # key never found
                    done = True
                cur = s
                out.append(line)
                continue
            if cur == sec and key_re.match(line):
                if not done:                        # replace commented key
                    out.append("%s = %s" % (key, val))
                    done = True
                continue                            # drop duplicate
            out.append(line)
        if not done:
            if cur == sec:                          # section at EOF
                out += ins
            else:                                   # section absent
                out += ["", "[%s]" % sec] + ins
        lines = out
        merged.append("%s.%s" % (sec, key))
    if merged:
        tmp = CONF + ".tmp"
        with open(tmp, "w") as f:
            f.write("\n".join(lines) + "\n")
        try:
            st = os.stat(CONF)          # keep the live file's mode + group
            os.chown(tmp, -1, st.st_gid)
            os.chmod(tmp, st.st_mode & 0o777)
        except OSError:
            os.chmod(tmp, 0o640)
        os.replace(tmp, CONF)
        _cp.read(CONF)
    return merged


def do_update_check():
    """Run the check through apc-nmc-update.sh so UI and CLI share one
    implementation (and one cache file the About page reads)."""
    if not os.path.exists(UPDATE_TOOL):
        return ("msg-err", "Updater is not installed on this system.")
    if update_busy():
        return ("msg-err", "An update is already in progress.")
    try:
        subprocess.run([UPDATE_TOOL, "--check"], check=False,
                       capture_output=True, timeout=30)
    except Exception:
        return ("msg-err", "Update check did not complete.")
    st = _load_json(UPDATE_STATE)
    if st.get("err"):
        return ("msg-err", "Update check failed: %s" % st["err"])
    if not st:
        return ("msg-err", "Update check produced no result.")
    if st.get("available"):
        return ("msg-ok", "Update available: %s &#8250; %s"
                % (esc(st.get("installed", "?")), esc(st.get("latest", "?"))))
    return ("msg-ok", "Software is up to date (%s)."
            % esc(st.get("installed", "?")))


def do_update_apply():
    """Queue the update unit and return immediately — it deploys the
    payload and restarts this service, so nothing can block on it."""
    if not os.path.exists(UPDATE_TOOL):
        return ("msg-err", "Updater is not installed on this system.")
    if update_busy():
        return ("msg-err", "An update is already in progress.")
    queue_update_status("starting update")
    try:
        subprocess.run(["systemctl", "start", "--no-block",
                        "apc-nmc-update.service"],
                       check=False, capture_output=True, timeout=15)
    except Exception:
        return ("msg-err", "Could not start the update service.")
    return ("msg-ok", "")


